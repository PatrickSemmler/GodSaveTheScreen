<#
.SYNOPSIS
  Erzeugt THIRD-PARTY-NOTICES.txt aus den NuGet-Paketen des App-Projekts (direkte und transitive Abhängigkeiten).
.DESCRIPTION
  Liest Lizenzangaben aus den .nuspec-Dateien im NuGet-Cache (Voraussetzung: dotnet restore wurde ausgeführt).
  Mit PowerShell 7 (pwsh) ausführen: Windows PowerShell 5 liest diese Datei sonst nicht als UTF-8 (Umlaute).
  Reine Build-Werkzeuge (Analyzer, Source-Generatoren) sind ebenfalls aufgeführt, weil sie im Paketbaum stehen.
#>
[CmdletBinding()]
param([string]$Output = (Join-Path (Split-Path -Parent $PSScriptRoot) 'THIRD-PARTY-NOTICES.txt'))

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

dotnet restore src/GodSaveTheScreen.App | Out-Null
$json = dotnet list src/GodSaveTheScreen.App package --include-transitive --format json | ConvertFrom-Json
$packages = $json.projects.frameworks.topLevelPackages + $json.projects.frameworks.transitivePackages |
    Where-Object { $_ } |
    Sort-Object id -Unique

$cache = (dotnet nuget locals global-packages --list) -replace '^global-packages:\s*', ''
$cache = $cache.Trim()

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('GodSaveTheScreen enthält bzw. verwendet die folgenden Drittanbieter-Komponenten.')
[void]$sb.AppendLine('GodSaveTheScreen includes or uses the following third-party components.')
[void]$sb.AppendLine('(Automatisch erzeugt mit build\generate-notices.ps1 / generated by build\generate-notices.ps1)')
[void]$sb.AppendLine('')

foreach ($package in $packages) {
    $id = $package.id
    $version = $package.resolvedVersion
    $nuspecPath = Join-Path $cache "$($id.ToLowerInvariant())\$version\$($id.ToLowerInvariant()).nuspec"
    $authors = ''; $license = ''; $url = ''; $copyright = ''
    if (Test-Path $nuspecPath) {
        [xml]$nuspec = Get-Content $nuspecPath
        $meta = $nuspec.package.metadata
        $authors = $meta.authors
        $url = if ($meta.projectUrl) { $meta.projectUrl } elseif ($meta.repository.url) { $meta.repository.url } else { '' }
        $copyright = $meta.copyright
        if ($meta.license) {
            $license = if ($meta.license.type -eq 'expression') { $meta.license.'#text' } else { "siehe Datei $($meta.license.'#text') im Paket" }
            # Lizenzdatei statt SPDX-Ausdruck: MIT am Anfang des Textes erkennen (z. B. PixiEditor.ColorPicker).
            $licenseFile = Join-Path (Split-Path $nuspecPath) $meta.license.'#text'
            if ($meta.license.type -eq 'file' -and (Test-Path $licenseFile) -and
                ((Get-Content $licenseFile -TotalCount 3) -join ' ') -match '^\W*(The )?MIT License') {
                $license = "MIT (Datei $($meta.license.'#text') im Paket)"
            }
        } elseif ($meta.licenseUrl) {
            $license = $meta.licenseUrl
        }
    }

    [void]$sb.AppendLine("$id $version")
    if ($authors) { [void]$sb.AppendLine("  Autor(en):  $authors") }
    if ($copyright) { [void]$sb.AppendLine("  Copyright:  $copyright") }
    if ($license) { [void]$sb.AppendLine("  Lizenz:     $license") }
    if ($url) { [void]$sb.AppendLine("  Projekt:    $url") }
    [void]$sb.AppendLine('')
}

